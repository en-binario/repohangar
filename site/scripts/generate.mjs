// Generates the parts of the site that must match the extension exactly, from the files the extension ships:
//   docs/reference/settings.md   ← package.json contributes.configuration
//   docs/reference/commands.md   ← package.json contributes.commands, keybindings and menus
//   docs/changelog.md            ← CHANGELOG.md
//   static/media/*.gif           ← media/*.gif (the README demos)
// It runs before `start` and `build` (npm pre-scripts). The outputs are gitignored: edit the sources instead.
// docs/versioning.md §6 requires the settings reference to be regenerated for every settings change; building the
// site does that.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(SITE, '..');
const GITHUB_BLOB = 'https://github.com/en-binario/repohangar/blob/main';

/** Settings sections, by the key segment after `repohangar.`; keys with no further segment are "General". */
const SECTIONS = {
  general: 'General',
  statusBar: 'Status bar',
  providers: 'Hosts and providers',
  dashboard: 'Dashboard',
  gitGraph: 'Git Graph',
  explorer: 'Explorer',
  mr: 'Merge requests',
  gitlab: 'GitLab',
};

const pkg = JSON.parse(readFileSync(join(REPO, 'package.json'), 'utf8'));
const GENERATED = '<!-- Generated by site/scripts/generate.mjs from the extension. Do not edit; edit the source. -->';

// ---------------------------------------------------------------------------------------------------- helpers

/** Escapes text for MDX outside inline code spans: `<`, `{` and `}` would otherwise be parsed as JSX. */
function escapeProse(text) {
  return text
    .split(/(`+[^`]*`+)/g)
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/\{/g, '&#123;').replace(/\}/g, '&#125;')))
    .join('');
}

const SETTING_IDS = new Set(
  [pkg.contributes.configuration].flat().flatMap((s) => Object.keys(s.properties)),
);

/**
 * VS Code's `#setting.id#` links in markdown descriptions become links to the setting's anchor, or plain code when
 * the setting belongs to VS Code or another extension.
 */
function settingLinks(text) {
  return text.replace(/`?#([\w.-]+)#`?/g, (_, id) => (SETTING_IDS.has(id) ? `[\`${id}\`](#${anchor(id)})` : `\`${id}\``));
}

/** A table cell: pipes are escaped even inside code spans (GitHub-flavoured Markdown tables). */
function cell(text) {
  return text.replace(/[\\|]/g, '\\$&').replace(/\n+/g, ' ');
}

/** The keys of an object setting whose values have a fixed shape (MR profiles, rules, …). */
function shapeOf(schema) {
  return schema.additionalProperties?.properties ?? schema.items?.properties ?? schema.properties ?? null;
}

function anchor(id) {
  return id.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

function inlineValue(value) {
  return '`' + JSON.stringify(value).replace(/,/g, ', ').replace(/:/g, ': ') + '`';
}

function describe(schema) {
  return settingLinks(escapeProse(schema.markdownDescription ?? schema.description ?? ''));
}

function write(rel, content) {
  const path = join(SITE, rel);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content.replace(/\n{3,}/g, '\n\n'));
  console.log(`generated ${rel}`);
}

// ---------------------------------------------------------------------------------------------------- settings

function settingsPage() {
  const sections = [pkg.contributes.configuration].flat();
  const properties = Object.assign({}, ...sections.map((s) => s.properties));
  const groups = new Map();
  for (const [id, schema] of Object.entries(properties)) {
    const parts = id.split('.');
    const group = parts.length > 2 ? parts[1] : 'general';
    if (!groups.has(group)) groups.set(group, []);
    groups.get(group).push([id, schema]);
  }

  const out = [
    '---',
    'title: Settings reference',
    'description: Every RepoHangar setting with its type, default value and allowed values.',
    'sidebar_label: Settings',
    // The table of contents lists the sections; setting ids are too long for the narrow column.
    'toc_max_heading_level: 2',
    '---',
    '',
    GENERATED,
    '',
    '# Settings reference',
    '',
    `RepoHangar has ${Object.keys(properties).length} settings. Open them with **Preferences: Open Settings (UI)** and`,
    'search for `repohangar`, or edit `settings.json`. User settings apply to every workspace; workspace settings',
    '(`.vscode/settings.json` or the `.code-workspace` file) are shared with everyone who opens the workspace.',
    '',
    'This page is generated from the extension manifest on every build, so it always matches the released version.',
    '',
  ];

  const order = [...Object.keys(SECTIONS), ...groups.keys()].filter((g, i, all) => groups.has(g) && all.indexOf(g) === i);
  for (const group of order) {
    out.push(`## ${SECTIONS[group] ?? group}`, '');
    for (const [id, s] of groups.get(group)) {
      out.push(`### \`${id}\` {#${anchor(id)}}`, '');
      const facts = [];
      const type = [s.type].flat().filter(Boolean).join(' | ');
      if (type) facts.push(`**Type:** \`${type}\``);
      if ('default' in s) {
        const json = JSON.stringify(s.default);
        facts.push(json.length <= 60 ? `**Default:** ${inlineValue(s.default)}` : '**Default:** see below');
      }
      if (s.scope) facts.push(`**Scope:** \`${s.scope}\``);
      if (facts.length) out.push(facts.join(' · '), '');
      if (s.deprecationMessage || s.markdownDeprecationMessage) {
        out.push(':::warning[Deprecated]', '', escapeProse(s.markdownDeprecationMessage ?? s.deprecationMessage), '', ':::', '');
      }
      const description = describe(s);
      if (description) out.push(description, '');
      if (s.enum) {
        const notes = s.markdownEnumDescriptions ?? s.enumDescriptions ?? [];
        out.push('| Value | Meaning |', '|---|---|');
        s.enum.forEach((v, i) => out.push(`| ${cell(inlineValue(v))} | ${cell(settingLinks(escapeProse(notes[i] ?? '')))} |`));
        out.push('');
      }
      const shape = shapeOf(s);
      if (shape) {
        const what = s.type === 'array' ? 'Each entry has these keys:' : 'Each value has these keys:';
        out.push(what, '', '| Key | Type | Description |', '|---|---|---|');
        for (const [k, sub] of Object.entries(shape)) {
          const subType = [sub.type].flat().filter(Boolean).join(' | ') + (sub.enum ? `: ${sub.enum.map((v) => JSON.stringify(v)).join(', ')}` : '');
          out.push(`| \`${k}\` | ${cell(subType ? '`' + subType + '`' : '')} | ${cell(describe(sub))} |`);
        }
        out.push('');
      }
      if ('default' in s && JSON.stringify(s.default).length > 60) {
        out.push('Default:', '', '```json', JSON.stringify(s.default, null, 2), '```', '');
      }
    }
  }
  return out.join('\n');
}

// ---------------------------------------------------------------------------------------------------- commands

function key(binding, mac) {
  const k = mac ? (binding.mac ?? binding.key) : binding.key;
  return k
    .split(' ')
    .map((chord) => chord.split('+').map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('+'))
    .map((chord) => `\`${chord}\``)
    .join(' ');
}

function commandsPage() {
  const { commands, keybindings = [], menus = {} } = pkg.contributes;
  const hidden = new Set((menus.commandPalette ?? []).filter((m) => m.when === 'false').map((m) => m.command));
  const out = [
    '---',
    'title: Commands and keyboard shortcuts',
    'description: Every RepoHangar command with its identifier and default keyboard shortcut.',
    'sidebar_label: Commands',
    '---',
    '',
    GENERATED,
    '',
    '# Commands and keyboard shortcuts',
    '',
    'Run commands from the Command Palette (`Ctrl+Shift+P`, `Cmd+Shift+P` on macOS) by typing `RepoHangar`. Bind any',
    'of them to a key in **Preferences: Open Keyboard Shortcuts** using its identifier. The dashboard has its own',
    'single-key shortcuts, listed in [The dashboard](../guide/dashboard.md#keys).',
    '',
    '## Default keyboard shortcuts',
    '',
    '| Command | Windows and Linux | macOS | When |',
    '|---|---|---|---|',
  ];
  const titleOf = (id) => {
    const c = commands.find((x) => x.command === id);
    return c ? `${c.category ? c.category + ': ' : ''}${c.title}` : id;
  };
  for (const b of keybindings) {
    out.push(`| **${escapeProse(titleOf(b.command))}** | ${key(b, false)} | ${key(b, true)} | ${cell(b.when ? '`' + b.when + '`' : 'Always')} |`);
  }
  out.push('', '## All commands', '', '| Command | Identifier |', '|---|---|');
  for (const c of commands) {
    const title = `${c.category ? c.category + ': ' : ''}${c.title}`;
    const note = hidden.has(c.command) ? ' <br/><small>Menus and the dashboard only, not in the Command Palette</small>' : '';
    out.push(`| **${escapeProse(title)}**${note} | \`${c.command}\` |`);
  }
  return out.join('\n') + '\n';
}

// ---------------------------------------------------------------------------------------------------- changelog

function changelogPage() {
  const source = readFileSync(join(REPO, 'CHANGELOG.md'), 'utf8').replace(/\r\n/g, '\n');
  let inFence = false;
  const body = source
    .split('\n')
    .filter((line, i) => !(i === 0 && line.startsWith('# ')))
    .map((line) => {
      if (line.startsWith('```')) inFence = !inFence;
      if (inFence || line.startsWith('```')) return line;
      // Relative links point into the repository; on the site they go to GitHub.
      const linked = line.replace(/\]\((?!https?:|#|mailto:)([^)]+)\)/g, (_, p) => `](${GITHUB_BLOB}/${p.replace(/^\.\//, '')})`);
      return escapeProse(linked);
    })
    .join('\n');
  return [
    '---',
    'title: Changelog',
    'description: What changed in each RepoHangar release.',
    '---',
    '',
    GENERATED,
    '',
    '# Changelog',
    body,
  ].join('\n');
}

// ---------------------------------------------------------------------------------------------------- media

function copyMedia() {
  const from = join(REPO, 'media');
  const to = join(SITE, 'static', 'media');
  rmSync(to, { recursive: true, force: true });
  mkdirSync(to, { recursive: true });
  for (const f of readdirSync(from).filter((f) => /\.(gif|png|svg)$/.test(f))) copyFileSync(join(from, f), join(to, f));
  console.log(`copied media/ → static/media/`);
}

write('docs/reference/settings.md', settingsPage());
write('docs/reference/commands.md', commandsPage());
write('docs/changelog.md', changelogPage());
copyMedia();
